function generate_simulink_parameters(xlsxFile, outputFile, selectedSheets, opts)
%GENERATE_SIMULINK_PARAMETERS Export accepted Excel parameters to a .m script.
% Version: 1.9.0 (Interface tools bundle).
%   generate_simulink_parameters('interfaces.xlsx', 'accepted_parameters.m')
%   generate_simulink_parameters('interfaces.xlsx', 'params.m', 'HVBat')
%   generate_simulink_parameters('interfaces.xlsx', 'params.m', ["HVBat","LVS"])
%   Third argument selects Excel sheets (default: all sheets).
%   Optional fourth opts.LogFcn callback receives live progress and warnings.
%
% Required Excel headers: Status, Parameter, Value, DataType, Element.
% Each sheet can contain a different header row. Multi-line Parameter and
% Value cells are matched line-by-line.

    if nargin < 2 || isempty(outputFile)
        outputFile = 'accepted_parameters.m';
    end
    if nargin < 3 || isempty(selectedSheets)
        selectedSheets = "all";
    end
    if nargin < 4, opts = struct(); end
    validateattributes(opts, {'struct'}, {'scalar'});
    if isfield(opts, 'LogFcn') && ~isempty(opts.LogFcn)
        validateattributes(opts.LogFcn, {'function_handle'}, {'scalar'});
    end
    xlsxFile = char(xlsxFile);
    outputFile = char(outputFile);
    if ~isfile(xlsxFile)
        error('Input file does not exist: %s', xlsxFile);
    end

    allSheets = string(sheetnames(xlsxFile));
    requested = strtrim(string(selectedSheets));
    if isscalar(requested) && strcmpi(requested, "all")
        sheets = allSheets;
    else
        requested = unique(requested(:).', 'stable');
        if isempty(requested) || any(ismissing(requested)) || any(strlength(requested) == 0)
            error('selectedSheets must contain at least one valid sheet name.');
        end
        missing = requested(~ismember(requested, allSheets));
        if ~isempty(missing)
            error('Excel sheet(s) not found: %s', strjoin(missing, ', '));
        end
        sheets = requested;
    end

    fid = fopen(outputFile, 'w', 'n', 'UTF-8');
    if fid < 0
        error('Cannot open output file: %s', outputFile);
    end
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%% Auto-generated from: %s\n', xlsxFile);
    fprintf(fid, '%% Generated by generate_simulink_parameters.m\n');
    fprintf(fid, '%% Generated at: %s\n\n', datestr(now, 'yyyy-mm-dd HH:MM:SS'));

    local_log(opts, '[PARAMETERS] %s -> %s (%d sheets)\n', xlsxFile, outputFile, numel(sheets));
    seen = containers.Map('KeyType', 'char', 'ValueType', 'char');
    total = 0;
    for s = 1:numel(sheets)
        sheet = sheets(s);
        local_log(opts, '[READ PARAMETERS] %d/%d: %s\n', s, numel(sheets), sheet);
        cells = readcell(xlsxFile, 'Sheet', sheet);
        if isempty(cells)
            continue;
        end

        required = {'Status', 'Parameter', 'Value', 'DataType', 'Element'};
        hdrRow = 0;
        cols = zeros(1, numel(required));
        for r = 1:min(size(cells, 1), 30)
            headers = cellfun(@cellText, cells(r, :), 'UniformOutput', false);
            headers = cellfun(@normalizeHeader, headers, 'UniformOutput', false);
            indices = zeros(1, numel(required));
            for k = 1:numel(required)
                idx = find(strcmp(headers, normalizeHeader(required{k})), 1);
                if ~isempty(idx)
                    indices(k) = idx;
                end
            end
            if all(indices > 0)
                hdrRow = r;
                cols = indices;
                break;
            end
        end
        if hdrRow == 0
            local_warn(opts, 'Sheet "%s": required headers not found. Skipping.', sheet);
            continue;
        end

        fprintf(fid, '\n%%%% Sheet: %s\n', sheet);
        fprintf(fid, '%% %s\n\n', repmat('-', 1, 55));
        count = 0;
        skippedBoolean = 0;
        for r = hdrRow + 1:size(cells, 1)
            if ~strcmpi(strtrim(cellText(cells{r, cols(1)})), 'Accept')
                continue;
            end
            names = splitLines(cells{r, cols(2)});
            values = splitLines(cells{r, cols(3)});
            dataTypes = splitLines(cells{r, cols(4)});
            element = strtrim(cellText(cells{r, cols(5)}));
            if isempty(names) || isempty(values)
                local_warn(opts, 'Sheet "%s", row %d: missing Parameter or Value.', sheet, r);
                continue;
            end
            if numel(values) ~= numel(names)
                local_warn(opts, 'Sheet "%s", row %d: %d names vs %d values. Skipping.', ...
                    sheet, r, numel(names), numel(values));
                continue;
            end
            if numel(dataTypes) == 1 && strcmpi(strtrim(dataTypes{1}), 'boolean')
                skippedBoolean = skippedBoolean + numel(names);
                continue;
            end
            if numel(dataTypes) == 1 && numel(names) > 1
                dataTypes = repmat(dataTypes, size(names));
            end
            if numel(dataTypes) ~= numel(names)
                local_warn(opts, 'Sheet "%s", row %d: invalid DataType count. Skipping.', sheet, r);
                continue;
            end

            for k = 1:numel(names)
                name = strtrim(names{k});
                dtype = strtrim(dataTypes{k});
                if strcmpi(dtype, 'boolean')
                    skippedBoolean = skippedBoolean + 1;
                    continue;
                end
                if ~isvarname(name) || isempty(dtype)
                    local_warn(opts, 'Sheet "%s", row %d: invalid name/data type "%s".', sheet, r, name);
                    continue;
                end
                if isKey(seen, name)
                    local_warn(opts, 'Duplicate parameter "%s" at sheet "%s", row %d (first: %s). Skipping.', ...
                        name, sheet, r, seen(name));
                    continue;
                end
                numericValue = str2double(strtrim(values{k}));
                if isnan(numericValue) || ~isfinite(numericValue)
                    local_warn(opts, 'Sheet "%s", row %d: non-numeric value "%s" for "%s". Skipping.', ...
                        sheet, r, values{k}, name);
                    continue;
                end
                seen(name) = sprintf('%s, row %d', sheet, r);
                fprintf(fid, '%s = Simulink.Parameter;\n', name);
                fprintf(fid, '%s.Value = %s;\n', name, strtrim(values{k}));
                fprintf(fid, '%s.Complexity = ''real'';\n', name);
                fprintf(fid, '%s.CoderInfo.StorageClass = ''Auto'';\n', name);
                fprintf(fid, '%s.Description = ''%s'';\n', name, escapeQuote(element));
                fprintf(fid, '%s.DataType = ''%s'';\n', name, escapeQuote(dtype));
                fprintf(fid, '%s.Min = [];\n', name);
                fprintf(fid, '%s.Max = [];\n', name);
                fprintf(fid, '%s.DocUnits = '''';\n\n', name);
                count = count + 1;
            end
        end
        total = total + count;
        local_log(opts, 'Sheet "%s": exported %d parameter(s), skipped %d boolean parameter(s).\n', ...
            sheet, count, skippedBoolean);
    end
    local_log(opts, 'Done: %d parameter(s) written to "%s".\n', total, outputFile);
end

function out = cellText(v)
    if ischar(v)
        out = v;
    elseif isstring(v) && isscalar(v) && ~ismissing(v)
        out = char(v);
    elseif isnumeric(v) && isscalar(v) && ~isnan(v)
        out = num2str(v, 17);
    else
        out = '';
    end
end

function out = normalizeHeader(in)
    out = lower(regexprep(strtrim(in), '[^a-zA-Z0-9]', ''));
end

function items = splitLines(v)
    in = cellText(v);
    if isempty(strtrim(in))
        items = {};
        return;
    end
    items = regexp(in, '\r\n|\n|\r', 'split');
    items = cellfun(@strtrim, items, 'UniformOutput', false);
    items = items(~cellfun(@isempty, items));
end

function out = escapeQuote(in)
    out = strrep(in, '''', '''''');
end

function local_log(opts, format, varargin)
    message = sprintf(format, varargin{:});
    fprintf('%s', message);
    if isfield(opts, 'LogFcn') && ~isempty(opts.LogFcn)
        opts.LogFcn(strtrim(message));
    end
end

function local_warn(opts, format, varargin)
    message = sprintf(format, varargin{:});
    warning('%s', message);
    if isfield(opts, 'LogFcn') && ~isempty(opts.LogFcn)
        opts.LogFcn(['[WARNING] ' message]);
    end
end
